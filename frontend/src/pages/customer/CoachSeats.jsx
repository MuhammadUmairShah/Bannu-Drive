import { useEffect, useState, useRef } from 'react';
import { Link, useParams, useNavigate } from 'react-router-dom';
import {
  ArrowLeft,
  RefreshCw,
  Clock,
  Phone,
  User,
} from 'lucide-react';

import api from '../../utils/api';
import { getErrorMessage } from '../../utils/errors';
import { formatCurrency } from '../../utils/formatters';
import { fmtDate, fmtTime } from '../../utils/dates';
import { toast } from '../../utils/toast';
import useScheduleSeats from '../../hooks/useScheduleSeats';
import { lostSeats, newIdempotencyKey } from '../../utils/seatSync';
import SyncBadge from '../../components/SyncBadge';
import { useAuth } from '../../context/AuthContext';
import SeatMap from '../../components/SeatMap';

export default function CoachSeats() {
  const { scheduleId } = useParams();
  const navigate = useNavigate();
  const { user } = useAuth();

  const [selected, setSelected] = useState([]);
  const [passengers, setPassengers] = useState({});
  const [holding, setHolding] = useState(false);

  /*
   * Keep selected seats available to the socket callback.
   */
  const selectedRef = useRef([]);
  selectedRef.current = selected;

  /*
   * True after OUR booking has successfully been created.
   *
   * This prevents realtime events related to our own
   * booking from being treated as another passenger.
   */
  const ownBookingRef = useRef(false);

  /*
   * IMPORTANT:
   *
   * This becomes true immediately when the booking
   * request starts.
   *
   * We need this because the backend can emit the
   * socket event before the POST request returns.
   */
  const holdingSeatsRef = useRef(false);

  /*
   * Idempotency information.
   *
   * If the request fails because of a temporary
   * network problem, the same key can be reused.
   */
  const attempt = useRef({
    sig: '',
    key: '',
  });

  /*
   * Live seat map.
   *
   * REST remains the source of truth.
   * Socket events provide fast updates.
   */
  const {
    data,
    loading,
    error,
    conn,
    lastSync,
    reload,
    refresh,
  } = useScheduleSeats(scheduleId, {
    onEvent: (p) => {
      /*
       * IMPORTANT FIX
       *
       * Ignore realtime updates while OUR booking
       * request is in progress.
       *
       * Otherwise the event generated by our own
       * booking can look like another passenger
       * taking the selected seat.
       */
      if (
        holdingSeatsRef.current ||
        ownBookingRef.current
      ) {
        return;
      }

      const currentSelected = selectedRef.current;

      if (!currentSelected.length) {
        return;
      }

      const lost = lostSeats(
        currentSelected,
        p
      );

      if (!lost.length) {
        return;
      }

      /*
       * Remove seats that were genuinely taken
       * by somebody else.
       */
      setSelected((current) =>
        current.filter(
          (seat) => !lost.includes(seat)
        )
      );

      toast.error(
        'Sorry, this seat was just booked by another passenger.'
      );
    },
  });

  /*
   * After a server re-sync, remove seats that are
   * no longer available.
   */
  useEffect(() => {
    if (!data) {
      return;
    }

    /*
     * Once our own booking has succeeded,
     * we are navigating to checkout.
     */
    if (ownBookingRef.current) {
      return;
    }

    /*
     * While the booking request is running,
     * don't modify the user's current selection.
     */
    if (holdingSeatsRef.current) {
      return;
    }

    const free = new Set(
      data.seats
        .filter(
          (seat) =>
            seat.status === 'AVAILABLE'
        )
        .map((seat) => seat.label)
    );

    setSelected((current) => {
      if (
        current.every((seat) =>
          free.has(seat)
        )
      ) {
        return current;
      }

      return current.filter((seat) =>
        free.has(seat)
      );
    });
  }, [data]);

  /*
   * Select/unselect a seat.
   */
  function toggle(label) {
    /*
     * Do not allow changes after successful
     * booking request.
     */
    if (
      ownBookingRef.current ||
      holdingSeatsRef.current
    ) {
      return;
    }

    setSelected((current) => {
      /*
       * Unselect.
       */
      if (current.includes(label)) {
        return current.filter(
          (seat) => seat !== label
        );
      }

      /*
       * Maximum seats.
       */
      const max =
        data?.schedule?.maxSeatsPerBooking || 4;

      if (current.length >= max) {
        toast.info(
          `You can book up to ${max} seats at a time.`
        );

        return current;
      }

      /*
       * Add seat.
       */
      return [...current, label].sort();
    });
  }

  /*
   * Update passenger information.
   */
  const setP = (
    seat,
    key,
    value
  ) => {
    setPassengers((current) => ({
      ...current,

      [seat]: {
        ...(current[seat] || {}),
        [key]: value,
      },
    }));
  };

  /*
   * Copy first passenger phone number
   * to other selected seats.
   */
  const copyFirst = () => {
    if (!selected.length) {
      return;
    }

    const first =
      passengers[selected[0]] || {};

    setPassengers((current) => ({
      ...current,

      ...Object.fromEntries(
        selected.slice(1).map((seat) => [
          seat,
          {
            ...first,
            name: '',
          },
        ])
      ),
    }));
  };

  /*
   * Hold selected seats.
   */
  async function holdSeats() {
    if (holding) {
      return;
    }

    if (
      holdingSeatsRef.current ||
      ownBookingRef.current
    ) {
      return;
    }

    /*
     * Make sure at least one seat is selected.
     */
    if (!selected.length) {
      toast.info(
        'Please select at least one seat.'
      );

      return;
    }

    /*
     * Validate every passenger.
     */
    for (const seat of selected) {
      const passenger =
        passengers[seat] || {};

      const name =
        (passenger.name || '').trim();

      if (name.length < 2) {
        toast.error(
          `Enter the passenger name for seat ${seat}.`
        );

        return;
      }

      const phone =
        (passenger.phone || '')
          .replace(/[\s-]/g, '');

      if (
        !/^(?:\+92|0)3\d{9}$/.test(
          phone
        )
      ) {
        toast.error(
          `Enter a valid mobile number for seat ${seat} (e.g. 03001234567).`
        );

        return;
      }
    }

    /*
     * Create/reuse idempotency key for
     * this exact seat selection.
     */
    const sig = selected.join(',');

    if (
      attempt.current.sig !== sig
    ) {
      attempt.current = {
        sig,
        key: newIdempotencyKey(),
      };
    }

    /*
     * VERY IMPORTANT:
     *
     * Set this BEFORE sending the request.
     *
     * The backend can emit the socket event
     * before the POST response reaches frontend.
     */
    holdingSeatsRef.current = true;

    try {
      setHolding(true);

      const response =
        await api.post(
          '/coach/orders',
          {
            scheduleId,

            seats: selected.map(
              (seat) => ({
                seat,

                passenger: {
                  name: passengers[
                    seat
                  ].name.trim(),

                  phone: passengers[
                    seat
                  ].phone.trim(),

                  gender:
                    passengers[
                      seat
                    ].gender || '',
                },
              })
            ),
          },
          {
            headers: {
              'Idempotency-Key':
                attempt.current.key,
            },
          }
        );

      /*
       * SUCCESS
       *
       * From this point this is our own booking.
       */
      ownBookingRef.current = true;

      /*
       * Reset idempotency state.
       */
      attempt.current = {
        sig: '',
        key: '',
      };

      /*
       * Clear selection before navigation.
       */
      setSelected([]);

      /*
       * Show correct success message.
       */
      toast.success(
        '🎉 Seats reserved successfully! Continue to payment.'
      );

      /*
       * Get order ID safely.
       */
      const orderId =
        response?.data?.order?._id;

      if (!orderId) {
        toast.error(
          'Seats were reserved, but the checkout could not be opened.'
        );

        /*
         * Allow the page to work normally again.
         */
        ownBookingRef.current = false;

        return;
      }

      /*
       * Go to checkout.
       */
      navigate(
        `/customer/checkout/${orderId}`
      );
    } catch (err) {
      const code =
        err?.response?.data?.code;

      /*
       * Server responded, so this attempt
       * should get a fresh idempotency key.
       */
      if (err?.response) {
        attempt.current = {
          sig: '',
          key: '',
        };
      }

      /*
       * Genuine seat conflict.
       *
       * ONLY this backend code should show
       * "another passenger" message.
       */
      if (code === 'SEAT_TAKEN') {
        const conflictSeats =
          err?.response?.data
            ?.conflictSeats || [];

        toast.error(
          'Sorry, this seat was just booked by another passenger.'
        );

        /*
         * Remove only the seats that were
         * actually reported as conflicting.
         */
        setSelected((current) =>
          current.filter(
            (seat) =>
              !conflictSeats.includes(
                seat
              )
          )
        );
      } else {
        /*
         * Other errors.
         */
        toast.error(
          getErrorMessage(
            err,
            'Could not reserve seats.'
          )
        );
      }

      /*
       * Re-sync from server.
       */
      refresh();
    } finally {
      /*
       * Request has finished.
       *
       * If successful, ownBookingRef remains true
       * and the page navigates to checkout.
       *
       * If failed, realtime conflict detection
       * becomes active again.
       */
      holdingSeatsRef.current = false;

      setHolding(false);
    }
  }

  /*
   * Loading state.
   */
  if (loading) {
    return (
      <div className="py-20 text-center">
        <RefreshCw className="w-7 h-7 animate-spin text-link mx-auto mb-3" />

        <p className="text-sm text-muted">
          Loading seat map...
        </p>
      </div>
    );
  }

  /*
   * Error state.
   */
  if (error || !data) {
    return (
      <div className="max-w-md mx-auto py-16 text-center space-y-3">
        <p className="text-sm text-danger">
          {error || 'Trip not found'}
        </p>

        <button
          type="button"
          onClick={reload}
          className="px-4 py-2 rounded-xl bg-fg text-bg hover:bg-primary hover:text-on-primary transition-colors text-xs font-semibold"
        >
          Try again
        </button>

        <div>
          <Link
            to="/customer/intercity"
            className="text-xs text-link font-semibold"
          >
            Back to search
          </Link>
        </div>
      </div>
    );
  }

  /*
   * Existing hold belonging to this customer.
   */
  const mineHeld =
    data.seats.find(
      (seat) =>
        seat.mine &&
        seat.status === 'HELD' &&
        seat.orderId
    );

  const s = data.schedule;

  /*
   * Total fare.
   */
  const total =
    selected.length * s.fare;

  return (
    <div className="max-w-5xl mx-auto space-y-5">

      {/* Header */}
      <div className="flex items-center gap-3">

        <Link
          to={`/customer/intercity?from=${encodeURIComponent(
            s.fromCity
          )}&to=${encodeURIComponent(
            s.toCity
          )}&date=${s.departureAt.slice(
            0,
            10
          )}`}
          className="p-2 bg-surface rounded-xl border border-line text-muted hover:bg-surface-2"
          aria-label="Back to results"
        >
          <ArrowLeft className="w-4 h-4" />
        </Link>

        <div className="min-w-0">

          <h1 className="text-lg sm:text-xl font-bold text-fg truncate">
            {s.fromCity} → {s.toCity}
          </h1>

          <p className="text-xs text-muted">
            {s.operator.companyName}

            {s.operator.isDemo
              ? ' (DEMO)'
              : ''}

            {' • '}

            {fmtDate(s.departureAt)}

            {' • '}

            {fmtTime(s.departureAt)}

            {' → '}

            {fmtTime(s.arrivalAt)}

            {' • '}

            {formatCurrency(s.fare)}
            {' / seat'}
          </p>

        </div>
      </div>

      {/* Existing hold */}
      {mineHeld && (
        <Link
          to={`/customer/checkout/${mineHeld.orderId}`}
          className="flex items-center gap-2 rounded-xl border border-primary/40 bg-primary-soft px-4 py-3 text-sm font-semibold text-link"
        >
          <Clock className="h-4 w-4" />

          You have seats on hold for this trip.
          Continue to payment →
        </Link>
      )}

      <div className="grid gap-5 lg:grid-cols-[minmax(0,22rem)_1fr]">

        {/* Seat map */}
        <div className="card p-4 sm:p-5">

          <p className="text-sm font-bold text-fg mb-1">
            Choose your seat
            {(
              s.maxSeatsPerBooking ||
              4
            ) > 1
              ? 's'
              : ''}
          </p>

          <p className="text-xs text-muted mb-2">
            {s.availableSeats} of{' '}
            {s.totalSeats} seats available
          </p>

          <div className="mb-4">
            <SyncBadge
              conn={conn}
              lastSync={lastSync}
              onRefresh={refresh}
            />
          </div>

          <SeatMap
            layout={data.layout}
            seats={data.seats}
            selected={selected}
            onToggle={toggle}
          />

        </div>

        {/* Passenger details */}
        <div className="card p-4 sm:p-5 space-y-4 self-start">

          <p className="text-sm font-bold text-fg">
            Passenger details
          </p>

          {selected.length === 0 ? (
            <p className="text-sm text-muted py-6 text-center border border-dashed border-field-line rounded-xl">
              Select a seat on the map to continue.
            </p>
          ) : (
            <>
              {selected.map(
                (seat, i) => (
                  <div
                    key={seat}
                    className="p-3 rounded-xl border border-line bg-surface-2 space-y-2"
                  >

                    <div className="flex items-center justify-between">

                      <p className="text-xs font-bold text-fg">
                        Seat {seat}
                      </p>

                      {i === 0 &&
                        selected.length > 1 && (
                          <button
                            type="button"
                            onClick={
                              copyFirst
                            }
                            className="text-xs font-semibold text-link"
                          >
                            Copy phone to other seats
                          </button>
                        )}

                    </div>

                    <div className="grid gap-2 sm:grid-cols-2">

                      {/* Passenger name */}
                      <label className="relative">

                        <User className="w-4 h-4 text-subtle absolute left-2.5 top-2.5" />

                        <input
                          type="text"
                          placeholder={
                            i === 0
                              ? `Passenger name (${user?.name || ''})`
                              : 'Passenger name'
                          }
                          maxLength={60}
                          value={
                            passengers[
                              seat
                            ]?.name || ''
                          }
                          onChange={(e) =>
                            setP(
                              seat,
                              'name',
                              e.target.value
                            )
                          }
                          className="w-full text-sm border border-field-line rounded-xl pl-8 pr-3 py-2 bg-field focus:outline-none focus:ring-2 focus:ring-primary text-fg"
                        />

                      </label>

                      {/* Phone */}
                      <label className="relative">

                        <Phone className="w-4 h-4 text-subtle absolute left-2.5 top-2.5" />

                        <input
                          type="tel"
                          inputMode="tel"
                          placeholder="03001234567"
                          maxLength={15}
                          value={
                            passengers[
                              seat
                            ]?.phone || ''
                          }
                          onChange={(e) =>
                            setP(
                              seat,
                              'phone',
                              e.target.value
                            )
                          }
                          className="w-full text-sm border border-field-line rounded-xl pl-8 pr-3 py-2 bg-field focus:outline-none focus:ring-2 focus:ring-primary text-fg"
                        />

                      </label>

                    </div>

                    {/* Gender */}
                    <div className="flex gap-4 text-xs text-muted">

                      {[
                        'male',
                        'female',
                      ].map(
                        (gender) => (
                          <label
                            key={gender}
                            className="flex items-center gap-1.5 capitalize"
                          >

                            <input
                              type="radio"
                              name={`g-${seat}`}
                              checked={
                                passengers[
                                  seat
                                ]?.gender ===
                                gender
                              }
                              onChange={() =>
                                setP(
                                  seat,
                                  'gender',
                                  gender
                                )
                              }
                            />

                            {gender}

                          </label>
                        )
                      )}

                    </div>

                  </div>
                )
              )}

              {/* Total */}
              <div className="flex items-center justify-between pt-3 border-t border-line">

                <div>

                  <p className="text-xs text-muted">
                    {selected.length}{' '}
                    seat
                    {selected.length > 1
                      ? 's'
                      : ''}{' '}
                    ({selected.join(', ')})
                  </p>

                  <p className="text-xl font-extrabold text-fg">
                    {formatCurrency(
                      total
                    )}
                  </p>

                </div>

                <button
                  type="button"
                  onClick={holdSeats}
                  disabled={
                    holding ||
                    holdingSeatsRef.current
                  }
                  className="px-6 py-3 rounded-xl bg-primary hover:bg-primary-hover disabled:opacity-60 text-on-primary text-sm font-semibold"
                >
                  {holding
                    ? 'Holding seats...'
                    : 'Hold seats & continue'}
                </button>

              </div>

              <p className="text-xs text-muted">
                Your seats are held for a few minutes
                while you choose how to pay (online or
                cash to the operator). Free cancellation
                until 2 hours before departure.
              </p>

            </>
          )}

        </div>

      </div>

    </div>
  );
}